    created = 0
    for name, content in DISTRACTORS.items():
        path = KNOWLEDGE_DIR / name
        if path.exists():
            print(f"  跳过（已存在）: {name}")
            continue
        path.write_text(content, encoding="utf-8")
        created += 1
        print(f"  已创建: {name}")

    print(f"\n共新增 {created} 篇，knowledge/ 现有 {len(list(KNOWLEDGE_DIR.glob('*.txt')))} 个 txt 文档")


